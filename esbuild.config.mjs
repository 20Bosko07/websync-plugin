import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";

// Follows the official Obsidian sample-plugin's esbuild setup:
// https://github.com/obsidianmd/obsidian-sample-plugin/blob/master/esbuild.config.mjs
//
// `@websync/shared` is deliberately NOT in `external` - its package.json
// points straight at its TS source (no build step / npm publish for it), so
// esbuild bundles that source directly into main.js, same as any other
// first-party module.

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
If you want to view the source, visit the websync-plugin repository,
src.
*/
`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  format: "cjs",
  target: "es2020",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: prod,
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
